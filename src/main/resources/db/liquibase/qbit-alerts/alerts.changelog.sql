   claimed_until TIMESTAMP,
   last_run_at TIMESTAMP,
   last_status VARCHAR(20),
   last_value VARCHAR(200),
   last_error VARCHAR(2000),
   last_elapsed_ms INTEGER,
   consecutive_failures INTEGER,
