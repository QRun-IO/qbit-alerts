-- changeset qbit-alerts:1
-- comment: A category of alerts for people ("Backups", "CDN"), optionally nested. The Alerts home groups by these, subscriptions target them, and every alert type belongs to one.
CREATE TABLE IF NOT EXISTS alerts_group (
   id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   name VARCHAR(100) NOT NULL,
   label VARCHAR(200) NOT NULL,
   parent_group_id INTEGER,
   icon VARCHAR(50),
   sort_order INTEGER,
   description TEXT,
   owner_team_id INTEGER,
   create_date TIMESTAMP,
   modify_date TIMESTAMP,
   CONSTRAINT pk_alerts_group PRIMARY KEY (id),
   CONSTRAINT uq_alerts_group UNIQUE (name)
);

-- changeset qbit-alerts:2
